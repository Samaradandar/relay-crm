import { useEffect, useState } from 'react';
import type { Lead, Team } from '@/api/types';
import { WAITING_LABEL, WAITING_SHORT } from '@/lib/leads';
import { Badge, TeamChip } from '@/components/ui/Badge';
import { Button } from '@/components/ui/Button';
import { Icon } from '@/components/ui/Icon';
import { formatWaiting } from '@/lib/format';

/** Re-renders every 30 s so "time waiting" counts up live. */
export function useNow(ms = 30_000) {
  const [now, setNow] = useState(Date.now());
  useEffect(() => { const t = window.setInterval(() => setNow(Date.now()), ms); return () => window.clearInterval(t); }, [ms]);
  return now;
}

/** Pool rows: company, contact, source, generated by, time waiting (live), routed team, waiting reason, Assign. */
export function PoolTable({ leads, teams, showTeam, onAssign, empty }: { leads: Lead[]; teams: Team[]; showTeam?: boolean; onAssign?: (l: Lead) => void; empty: string }) {
  const now = useNow();
  if (leads.length === 0) return <div className="panel flex items-center gap-3 p-5 text-ink-2"><span className="grid h-8 w-8 place-items-center rounded-full bg-success-soft text-success"><Icon name="check" /></span>{empty}</div>;
  return <div className="overflow-x-auto rounded-lg border border-line bg-surface-1">
    <table className="w-full border-collapse text-sm">
      <thead><tr>{['Company', 'Source', 'Added by', 'Waiting', ...(showTeam ? ['Routed to'] : []), 'Why it is waiting', ''].map((h) => <th key={h} className="whitespace-nowrap border-b border-line bg-surface-2 px-3 py-2.5 text-left text-xs font-semibold text-ink-2">{h}</th>)}</tr></thead>
      <tbody>{leads.map((l) => {
        const hrs = (now - Date.parse(l.pooledAt)) / 3_600_000; const team = teams.find((t) => t.id === l.teamId);
        return <tr key={l.id} className="hover:bg-surface-3">
          <td className="border-b border-line px-3 py-2.5"><span className="flex flex-col"><span className="text-body-strong">{l.company}</span><span className="text-xs text-ink-3">{l.contactName}{l.city ? ` · ${l.city}` : ''}</span></span></td>
          <td className="whitespace-nowrap border-b border-line px-3 text-ink-2">{l.source}</td>
          <td className="whitespace-nowrap border-b border-line px-3 text-ink-2">{l.generatedByName}</td>
          <td className="whitespace-nowrap border-b border-line px-3"><span className={hrs >= 24 ? 'font-semibold text-danger' : hrs >= 4 ? 'font-semibold text-warning' : 'text-ink'}><Icon name="clock" size={14} className="mr-1 inline align-[-2px]" />{formatWaiting(l.pooledAt, now)}</span></td>
          {showTeam && <td className="whitespace-nowrap border-b border-line px-3">{team ? <TeamChip name={team.name} color={team.color} /> : '—'}</td>}
          <td className="whitespace-nowrap border-b border-line px-3">{l.waitingReason ? <span title={WAITING_LABEL[l.waitingReason]}><Badge tone="warning" icon="alert">{WAITING_SHORT[l.waitingReason]}</Badge></span> : <Badge tone="accent" dot>Being assigned</Badge>}</td>
          <td className="whitespace-nowrap border-b border-line px-3 text-right">{onAssign && <Button size="sm" variant="secondary" icon="user" onClick={() => onAssign(l)}>Assign</Button>}</td>
        </tr>;
      })}</tbody>
    </table>
  </div>;
}
